#!/bin/sh
set -eu

# Prevent macOS BSD tar from injecting ._* AppleDouble files
export COPYFILE_DISABLE=1

# build-ipk.sh -- Package uapi-traffic-hosts into OpenWrt .ipk and signed .apk packages

RAW_VERSION="${1:-1.0.0}"
DEST_DIR="${2:-dist}"
PKG_NAME="uapi-traffic-hosts"
ARCH="all"

# Normalize version numbers
CLEAN_VER="$(echo "$RAW_VERSION" | sed 's/^v//; s/-.*//')"
IPK_VER="${CLEAN_VER}-1"
APK_VER="${CLEAN_VER}-r1"

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SRC_PLUGIN="${SCRIPT_DIR}/traffic.hosts.uc"
KEY_PRIV="${SCRIPT_DIR}/keys/orangutan.rsa"
KEY_PUB="${SCRIPT_DIR}/keys/orangutan.rsa.pub"

if [ ! -f "${SRC_PLUGIN}" ]; then
    echo "Error: ${SRC_PLUGIN} not found" >&2
    exit 1
fi

mkdir -p "${DEST_DIR}"
DEST_DIR="$(cd "${DEST_DIR}" && pwd)"
TMP_DIR="$(mktemp -d 2>/dev/null || mktemp -d -t 'pkg_build')"
trap 'rm -rf "${TMP_DIR}"' EXIT INT TERM

# 1. Prepare payload filesystem
DATA_DIR="${TMP_DIR}/payload"
mkdir -p "${DATA_DIR}/usr/share/uapi/resources"
cp "${SRC_PLUGIN}" "${DATA_DIR}/usr/share/uapi/resources/traffic.hosts.uc"
chmod 644 "${DATA_DIR}/usr/share/uapi/resources/traffic.hosts.uc"

INSTALLED_SIZE=$(du -sk "${DATA_DIR}" | cut -f1)
BUILD_DATE=$(date +%s 2>/dev/null || date -u +%s)

# --- 2. Build .ipk package (for OpenWrt opkg) ---
IPK_DIR="${TMP_DIR}/ipk"
mkdir -p "${IPK_DIR}"
( cd "${DATA_DIR}" && tar -czf "${IPK_DIR}/data.tar.gz" . )

mkdir -p "${IPK_DIR}/control"
cat << EOF > "${IPK_DIR}/control/control"
Package: ${PKG_NAME}
Version: ${IPK_VER}
Depends: uapi, nlbwmon
Section: net
Architecture: ${ARCH}
Maintainer: LAN-Orangutan
Installed-Size: ${INSTALLED_SIZE}
Description: OpenWrt uapi traffic plugin for LAN-Orangutan bandwidth telemetry
EOF

cat << 'EOF' > "${IPK_DIR}/control/postinst"
#!/bin/sh
if [ -f /usr/share/uapi/main.uc ]; then
    if ! grep -q '"traffic:hosts"' /usr/share/uapi/main.uc; then
        sed -i '/const RESOURCES = {/a \	"traffic:hosts": handler.make_collection(load_resource("traffic:hosts")),' /usr/share/uapi/main.uc
    fi
    /etc/init.d/uhttpd restart >/dev/null 2>&1 || true
fi
exit 0
EOF
chmod 755 "${IPK_DIR}/control/postinst"

cat << 'EOF' > "${IPK_DIR}/control/prerm"
#!/bin/sh
if [ -f /usr/share/uapi/main.uc ]; then
    sed -i '/"traffic:hosts"/d' /usr/share/uapi/main.uc
    /etc/init.d/uhttpd restart >/dev/null 2>&1 || true
fi
exit 0
EOF
chmod 755 "${IPK_DIR}/control/prerm"

( cd "${IPK_DIR}/control" && tar -czf "${IPK_DIR}/control.tar.gz" . )
echo "2.0" > "${IPK_DIR}/debian-binary"

OUTPUT_IPK="${DEST_DIR}/${PKG_NAME}_${IPK_VER}_${ARCH}.ipk"
( cd "${IPK_DIR}" && tar -czf "${OUTPUT_IPK}" ./debian-binary ./data.tar.gz ./control.tar.gz )
echo "Built OpenWrt .ipk: ${OUTPUT_IPK}"

# --- 3. Build .apk package (for modern OpenWrt apk v2) ---
# An APK package consists of concatenated gzip streams:
# [Signature Stream (optional)] + [Control Stream (.PKGINFO + scripts)] + [Data Stream (files)]

APK_BUILD="${TMP_DIR}/apk_build"
mkdir -p "${APK_BUILD}/data" "${APK_BUILD}/control"
cp -r "${DATA_DIR}/"* "${APK_BUILD}/data/"

# Create data stream (pack usr directly without leading ./)
DATA_TAR="${APK_BUILD}/data.tar.gz"
( cd "${APK_BUILD}/data" && tar -czf "${DATA_TAR}" usr )

if command -v sha256sum >/dev/null 2>&1; then
    DATA_HASH=$(sha256sum "${DATA_TAR}" | cut -d' ' -f1)
else
    DATA_HASH=$(shasum -a 256 "${DATA_TAR}" | cut -d' ' -f1)
fi

# Create control stream
cat << EOF > "${APK_BUILD}/control/.PKGINFO"
# Generated by LAN-Orangutan
pkgname = ${PKG_NAME}
pkgver = ${APK_VER}
pkgdesc = OpenWrt uapi traffic plugin for LAN-Orangutan bandwidth telemetry
url = https://github.com/spoutin/LAN-Orangutan
builddate = ${BUILD_DATE}
packager = LAN-Orangutan
size = $((INSTALLED_SIZE * 1024))
arch = ${ARCH}
origin = ${PKG_NAME}
license = MIT
depend = uapi
depend = nlbwmon
datahash = ${DATA_HASH}
EOF
chmod 644 "${APK_BUILD}/control/.PKGINFO"

cat << 'EOF' > "${APK_BUILD}/control/.post-install"
#!/bin/sh
if [ -f /usr/share/uapi/main.uc ]; then
    if ! grep -q '"traffic:hosts"' /usr/share/uapi/main.uc; then
        sed -i '/const RESOURCES = {/a \	"traffic:hosts": handler.make_collection(load_resource("traffic:hosts")),' /usr/share/uapi/main.uc
    fi
    /etc/init.d/uhttpd restart >/dev/null 2>&1 || true
fi
exit 0
EOF
chmod 755 "${APK_BUILD}/control/.post-install"

cat << 'EOF' > "${APK_BUILD}/control/.pre-deinstall"
#!/bin/sh
if [ -f /usr/share/uapi/main.uc ]; then
    sed -i '/"traffic:hosts"/d' /usr/share/uapi/main.uc
    /etc/init.d/uhttpd restart >/dev/null 2>&1 || true
fi
exit 0
EOF
chmod 755 "${APK_BUILD}/control/.pre-deinstall"

CONTROL_TAR="${APK_BUILD}/control.tar.gz"
( cd "${APK_BUILD}/control" && tar -czf "${CONTROL_TAR}" .PKGINFO .post-install .pre-deinstall )

# Create signature stream if RSA private key exists
OUTPUT_APK="${DEST_DIR}/${PKG_NAME}-${APK_VER}.apk"
OUTPUT_APK_ALT="${DEST_DIR}/${PKG_NAME}_${CLEAN_VER}_${ARCH}.apk"

if [ -f "${KEY_PRIV}" ] && [ -f "${KEY_PUB}" ]; then
    SIG_DIR="${APK_BUILD}/sig"
    mkdir -p "${SIG_DIR}"
    KEY_PUB_NAME="$(basename "${KEY_PUB}")"
    openssl dgst -sha1 -sign "${KEY_PRIV}" "${CONTROL_TAR}" > "${SIG_DIR}/.SIGN.RSA.${KEY_PUB_NAME}"
    SIG_TAR="${APK_BUILD}/sig.tar.gz"
    ( cd "${SIG_DIR}" && tar -czf "${SIG_TAR}" ".SIGN.RSA.${KEY_PUB_NAME}" )

    # Concatenate [sig] + [control] + [data]
    cat "${SIG_TAR}" "${CONTROL_TAR}" "${DATA_TAR}" > "${OUTPUT_APK}"
    cp "${KEY_PUB}" "${DEST_DIR}/${KEY_PUB_NAME}"
    echo "Signed OpenWrt .apk with ${KEY_PUB_NAME}"
else
    # Concatenate [control] + [data]
    cat "${CONTROL_TAR}" "${DATA_TAR}" > "${OUTPUT_APK}"
fi

cp "${OUTPUT_APK}" "${OUTPUT_APK_ALT}"
echo "Built OpenWrt .apk: ${OUTPUT_APK} (and ${OUTPUT_APK_ALT})"
